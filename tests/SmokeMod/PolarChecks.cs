using System;
using System.Linq;
using Vintagestory.API.Server;
using Wmap.Integrations;
using Wmap.Core;

public static class PolarChecks
{
    public static string Run(ICoreServerAPI api, WorldSource source)
    {
        object system = api.ModLoader.Systems.FirstOrDefault(s => s.GetType().FullName == "CylinderWorld.CylinderWorldCore");
        object p = WorldSource.Member(system, "Params");
        if (p == null || WorldSource.Member(p, "HasWalls") is not true) return "Polar adapter: not applicable";
        double N(string name) => Convert.ToDouble(WorldSource.Member(p, name));
        int sea = api.World.SeaLevel, top = Math.Min((int)N("WallTopY"), api.WorldManager.MapSizeY - 2);
        double x = source.Info.StartX + source.Info.Width / 2, length = N("WorldLength");
        foreach (double z in new[] { 0.0, length - 1 })
        {
            var sample = source.Sample(x, z);
            if (sample.Kind != 4 || sample.Height != top) throw new Exception("Missing real Cylinder wall at " + z);
        }
        if (WorldSource.Member(p, "EarthPolarIce") is true)
            return "Polar adapter: Earth mode (both wall tops checked; generated-chunk comparisons follow)";
        var flat = new CylinderSurface(p, api.WorldManager.MapSizeY, sea).Bind((_, _) => new MapSample(sea - 40, 39, 2));
        int ice = 0;
        var getColumn = p.GetType().GetMethod("GetPolarColumn");
        foreach (double edge in new[] { 0.0, length })
        for (double d = N("WallFaceMax") + 40; d < N("PolarZoneDepth"); d += 127)
        {
            double z = Math.Floor(edge == 0 ? d : length - d);
            object column = getColumn.Invoke(p, new object[] { Math.Floor(x) + .5, z + .5 });
            int iceTop = Convert.ToInt32(WorldSource.Member(column, "IceTop"));
            if (iceTop < sea) continue;
            var sample = flat(x, z);
            if (sample.Kind != 3 || sample.Height < Math.Min(iceTop, top)) throw new Exception("Polar ice geometry disagrees with installed GetPolarColumn");
            ice++;
        }
        if (N("ApronDepth") > 100 && ice == 0) throw new Exception("No ice-sheet samples validated");
        return $"Polar adapter: PASS (both wall tops, {ice} ice-sheet samples against installed Cylinder geometry; no chunks generated by sampler)";
    }
}
